import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import fs from 'node:fs/promises';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const browser=await chromium.launch({headless:true,...(process.platform==='win32'?{channel:'msedge'}:{})});
const context=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
const page=await context.newPage();const results=[];
try {
  await page.goto(`${process.env.EDITOR_TEST_URL || 'http://127.0.0.1:5174'}/tests/editorHarness.html`);
  await page.locator('canvas').waitFor();
  const scrubber = await page.locator('#timeline-audio-scrubber-slider').evaluate(e => ({height:e.getBoundingClientRect().height,bottom:e.getBoundingClientRect().bottom,parentBottom:e.parentElement.getBoundingClientRect().bottom}));
  assert.ok(scrubber.height >= 44 && scrubber.bottom <= scrubber.parentBottom + 1);
  const open = async name => {await page.locator('#editor-btn-more-hub').click();await page.getByRole('button',{name,exact:false}).click();};
  const close=()=>page.getByRole('button',{name:'Tutup konfigurasi studio',exact:true}).click();
  await open('Difficulty & JSON');
  await page.getByRole('button',{name:'Tambah Slot',exact:true}).click();
  await page.getByPlaceholder('Nama difficulty baru (misal: Master, Chaos)...').fill('Added');
  await page.getByRole('button',{name:'Simpan',exact:true}).click();
  await page.waitForFunction(()=>Boolean(JSON.parse(localStorage.getItem('AUDIT_FIXTURE')).charts.Added));
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('AUDIT_FIXTURE')).charts.Audit.notes.length),23);
  await page.locator('summary[aria-label="Tindakan slot Added"]').click();
  await page.getByRole('button',{name:'Hapus slot',exact:true}).click();
  await page.getByRole('button',{name:'Konfirmasi hapus',exact:true}).click();
  await page.waitForFunction(()=>!JSON.parse(localStorage.getItem('AUDIT_FIXTURE')).charts.Added);
  await close();results.push('add/delete difficulty preserve existing notes and slot identity');
  await page.getByRole('button',{name:'Hapus',exact:true}).click();
  await page.locator('canvas').click({position:{x:90*0.1,y:30}});await page.waitForTimeout(1400);
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('AUDIT_FIXTURE')).charts.Audit.notes.length),22);
  await page.getByRole('button',{name:/Undo \(Ctrl\+Z\)/}).click();await page.waitForTimeout(1400);
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('AUDIT_FIXTURE')).charts.Audit.notes.length),23);
  results.push('erase targets the note and one Undo restores it');
  const height=(await page.locator('canvas').boundingBox()).height;
  await page.locator('canvas').click({position:{x:180,y:height-10}});
  assert.equal(Number(await page.getByRole('slider',{name:'Seek linimasa audio',exact:true}).inputValue()),2);
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('AUDIT_FIXTURE')).charts.Audit.notes.length),23);
  results.push('ruler seek updates playhead without changing notes');
  await open('Hapus Semua Note');
  await page.getByRole('textbox').fill('HAPUS');
  await page.getByRole('button',{name:/Hapus Semua \(23 Note\)/}).click();await page.waitForTimeout(1400);
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('AUDIT_FIXTURE')).charts.Audit.notes.length),0);
  await close();await page.getByRole('button',{name:/Undo \(Ctrl\+Z\)/}).click();await page.waitForTimeout(1400);
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('AUDIT_FIXTURE')).charts.Audit.notes.length),23);
  results.push('clear requires typed confirmation and Undo restores exact note count');
  await page.getByRole('button',{name:'Tap',exact:true}).first().click();
  await page.getByRole('slider',{name:'Seek linimasa audio',exact:true}).fill('4');
  await page.getByRole('button',{name:'Tap',exact:true}).first().click();
  for(const key of ['d','f','j','k']) await page.keyboard.press(key);
  await page.waitForTimeout(1400);
  const notes=await page.evaluate(()=>JSON.parse(localStorage.getItem('AUDIT_FIXTURE')).charts.Audit.notes);
  assert.deepEqual(notes.filter(n=>n.time===4).map(n=>n.lane).sort(),[0,1,2,3]);results.push('D/F/J/K insert all four lanes at snapped playhead');
  assert.equal(await page.locator('button').first().evaluate(e=>getComputedStyle(e).transitionDuration),'0s');
  await page.evaluate(()=>document.documentElement.style.fontSize='32px');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  results.push('reduced motion removes transitions; 200% root text size has no horizontal page overflow');
}catch(error){process.exitCode=1;results.push(String(error.stack||error));}
finally{await fs.writeFile('docs/editor-additional-results.json',JSON.stringify(results,null,2));console.log(JSON.stringify(results,null,2));await browser.close();}
